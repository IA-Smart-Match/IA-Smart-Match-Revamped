"""Team workspaces against a real PostgreSQL (CE-WORKSPACE, design spec §15, §11).

``tests/unit/test_exercise_workspace_router.py`` proves the routes over a fake
repository. A fake repository cannot prove any of the four things that actually
keep six teams apart in a classroom, and all four are database properties:

* **The race.** Two laptops on team 3 entering at the same moment produce one
  row, because ``uq_exercise_team_workspace_dataset_team`` admits one and the
  loser's insert is discarded — not because one of them checked first.
* **Isolation.** A reset deletes this team's overlay, settings and runs and
  leaves every other team's untouched, including their seeds. Justin's
  checklist calls this out by name.
* **The seed.** Regenerated by a reset, and it is a real column with a real
  ``BIGINT`` range that a 64-bit draw would overflow.
* **"The active dataset."** Most recently uploaded wins, and the rule has to
  hold against rows whose ``uploaded_at`` values are close enough to tie.

Runs against its own scratch database, migrated to head, and dropped
afterwards; skipped where no PostgreSQL is reachable.
"""

from __future__ import annotations

import uuid
from collections.abc import Iterator
from datetime import UTC, datetime, timedelta

import pytest

pytest.importorskip("sqlalchemy")

import sqlalchemy as sa
from migration_harness import alembic, connected, scratch_database
from smartmatch_domain.exercise.workspace_token import (
    derive_workspace_token,
    hash_workspace_token,
)
from smartmatch_persistence.exercise import schema
from smartmatch_persistence.exercise.workspace_repository import (
    ExerciseWorkspaceRepository,
    active_dataset,
)
from sqlalchemy import Engine
from sqlalchemy.orm import Session, sessionmaker

pytestmark = pytest.mark.integration

#: Not a real key, and assembled from pieces for the reason the unit file gives:
#: ``tools/scan_forbidden.py`` matches the shape of a committed credential, and
#: a test that needs an exception from that rule is a test written badly.
_SECRET = "-".join(("integration", "only", "exercise", "workspace", "key"))


@pytest.fixture
def exercise_sessions(engine: Engine) -> Iterator[sessionmaker[Session]]:
    """A session factory over a scratch database migrated to head.

    Its own database rather than the shared development one, because this file
    deletes rows: a ``DELETE FROM exercise_profile_overlay`` run against
    somebody's working database is somebody's work gone.
    """
    with scratch_database(engine) as url:
        alembic(url, "head", expect_success=True)
        with connected(url) as scratch:
            yield sessionmaker(bind=scratch, expire_on_commit=False, future=True)


def _insert_dataset(
    session: Session, *, label: str, uploaded_at: datetime | None = None, invite_limit: int = 30
) -> uuid.UUID:
    """One ``exercise_dataset`` row, written directly.

    CE-INGEST-CORE owns the repository that writes these for real; this file
    must not anticipate its shape, so it writes the columns the migration
    declares and nothing more.
    """
    dataset_id = uuid.uuid4()
    values: dict[str, object] = {
        "id": dataset_id,
        "label": label,
        "source_filename": f"{label}.csv",
        "row_count": 300,
        "checksum": uuid.uuid4().hex,
        "invite_limit": invite_limit,
    }
    if uploaded_at is not None:
        values["uploaded_at"] = uploaded_at
    session.execute(sa.insert(schema.exercise_dataset).values(**values))
    # One profile and one event, because the overlay, the saved setting and the
    # result run all carry composite foreign keys into them. Not a fixture of
    # the exercise's data — the real 300 arrive with CE-INGEST-CORE — just the
    # two rows a team's work has to hang off.
    session.execute(
        sa.insert(schema.exercise_profile).values(
            dataset_id=dataset_id,
            profile_no=1,
            display_name="A made-up person",
        )
    )
    session.execute(
        sa.insert(schema.exercise_event).values(
            dataset_id=dataset_id,
            event_key="northline",
            name="Northline Analytics",
            sequence=1,
            is_exercise_event=True,
        )
    )
    session.commit()
    return dataset_id


def _seed_of(session: Session, workspace_id: uuid.UUID) -> int:
    table = schema.exercise_team_workspace
    return int(
        session.execute(sa.select(table.c.seed).where(table.c.id == workspace_id)).scalar_one()
    )


