def _add_team_work(session: Session, *, workspace_id: uuid.UUID, dataset_id: uuid.UUID) -> None:
    """One overlay row, one saved setting and one result run for a team.

    Written directly rather than through the repositories that will own them
    (CE-SIMULATION, CE-INSTRUCTOR), because what is being tested is that a
    reset deletes them, not how they arrive.
    """
    session.execute(
        sa.insert(schema.exercise_profile_overlay).values(
            workspace_id=workspace_id,
            dataset_id=dataset_id,
            profile_no=1,
            card_career_goal="PLACEHOLDER (OQ-CE-01)",
        )
    )
    session.execute(
        sa.insert(schema.exercise_saved_setting).values(
            id=uuid.uuid4(),
            workspace_id=workspace_id,
            dataset_id=dataset_id,
            event_key="northline",
            name="even weights",
            weights={"same_major": 0.25},
        )
    )
    session.execute(
        sa.insert(schema.exercise_result_run).values(
            id=uuid.uuid4(),
            workspace_id=workspace_id,
            dataset_id=dataset_id,
            event_key="northline",
            round=1,
            seats_empty=52,
            email_everyone={},
        )
    )
    session.execute(
        sa.update(schema.exercise_team_workspace)
        .where(schema.exercise_team_workspace.c.id == workspace_id)
        .values(asking_choice="small_reward", refreshed_at=datetime.now(UTC))
    )
    session.commit()


def _child_counts(session: Session, workspace_id: uuid.UUID) -> tuple[int, int, int]:
    return tuple(  # type: ignore[return-value]
        session.execute(
            sa.select(sa.func.count())
            .select_from(table)
            .where(table.c.workspace_id == workspace_id)
        ).scalar_one()
        for table in (
            schema.exercise_profile_overlay,
            schema.exercise_saved_setting,
            schema.exercise_result_run,
        )
    )


def test_a_reset_clears_one_team_and_nothing_else(
    exercise_sessions: sessionmaker[Session],
) -> None:
    """Justin's checklist line, as an assertion about two teams' rows.

    The point is not only that team 1 is empty afterwards. It is that team 2 is
    untouched — its overlay, its settings, its run, *and* its seed, which a
    reset that regenerated seeds by dataset rather than by workspace would have
    changed without deleting anything visible.
    """
    repository = ExerciseWorkspaceRepository()
    with exercise_sessions() as session:
        dataset_id = _insert_dataset(session, label="reset-isolation")
        first = repository.get_or_create_workspace(
            session, dataset_id=dataset_id, team_number=1, workspace_secret=_SECRET
        )
        second = repository.get_or_create_workspace(
            session, dataset_id=dataset_id, team_number=2, workspace_secret=_SECRET
        )
        session.commit()
        _add_team_work(session, workspace_id=first.id, dataset_id=dataset_id)
        _add_team_work(session, workspace_id=second.id, dataset_id=dataset_id)

        first_seed_before = _seed_of(session, first.id)
        second_seed_before = _seed_of(session, second.id)
        assert _child_counts(session, first.id) == (1, 1, 1)

        repository.reset_team(session, workspace_id=first.id)
        session.commit()

        assert _child_counts(session, first.id) == (0, 0, 0)
        assert _child_counts(session, second.id) == (1, 1, 1)
        assert _seed_of(session, first.id) != first_seed_before
        assert _seed_of(session, second.id) == second_seed_before

        table = schema.exercise_team_workspace
        row = session.execute(
            sa.select(
                table.c.asking_choice, table.c.refreshed_at, table.c.workspace_token_hash
            ).where(table.c.id == first.id)
        ).one()
    assert row.asking_choice is None
    assert row.refreshed_at is None
    assert row.workspace_token_hash == hash_workspace_token(
        derive_workspace_token(secret=_SECRET, workspace_id=first.id)
    ), "a reset keeps the team's token: it clears work, it does not log anybody out"


def test_a_reset_keeps_the_workspace_row(exercise_sessions: sessionmaker[Session]) -> None:
    repository = ExerciseWorkspaceRepository()
    with exercise_sessions() as session:
        dataset_id = _insert_dataset(session, label="reset-keeps-row")
        workspace = repository.get_or_create_workspace(
            session, dataset_id=dataset_id, team_number=4, workspace_secret=_SECRET
        )
        session.commit()
        repository.reset_team(session, workspace_id=workspace.id)
        session.commit()
        again = repository.get_or_create_workspace(
            session, dataset_id=dataset_id, team_number=4, workspace_secret=_SECRET
        )
        session.commit()
    assert again == workspace


def test_a_reset_of_an_unknown_workspace_changes_nothing(
    exercise_sessions: sessionmaker[Session],
) -> None:
    """A workspace id that names no row is not an error and not a wildcard."""
    repository = ExerciseWorkspaceRepository()
    with exercise_sessions() as session:
        dataset_id = _insert_dataset(session, label="reset-unknown")
        workspace = repository.get_or_create_workspace(
            session, dataset_id=dataset_id, team_number=5, workspace_secret=_SECRET
        )
        session.commit()
        _add_team_work(session, workspace_id=workspace.id, dataset_id=dataset_id)
        seed_before = _seed_of(session, workspace.id)

        repository.reset_team(session, workspace_id=uuid.uuid4())
        session.commit()

        assert _child_counts(session, workspace.id) == (1, 1, 1)
        assert _seed_of(session, workspace.id) == seed_before


