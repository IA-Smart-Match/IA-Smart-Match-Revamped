def test_no_dataset_is_a_real_answer(exercise_sessions: sessionmaker[Session]) -> None:
    with exercise_sessions() as session:
        assert active_dataset(session) is None


def test_the_most_recently_uploaded_dataset_is_the_active_one(
    exercise_sessions: sessionmaker[Session],
) -> None:
    now = datetime.now(UTC)
    with exercise_sessions() as session:
        _insert_dataset(session, label="first", uploaded_at=now - timedelta(hours=2))
        newest = _insert_dataset(session, label="second", uploaded_at=now)
        _insert_dataset(session, label="older", uploaded_at=now - timedelta(days=9))
        found = active_dataset(session)
    assert found is not None
    assert found.id == newest
    assert found.label == "second"
    assert found.invite_limit == 30


def test_a_tie_on_upload_time_still_has_one_answer(
    exercise_sessions: sessionmaker[Session],
) -> None:
    """Two rows written in the same tick order by id, so every reader agrees."""
    stamp = datetime.now(UTC)
    with exercise_sessions() as session:
        first = _insert_dataset(session, label="a", uploaded_at=stamp)
        second = _insert_dataset(session, label="b", uploaded_at=stamp)
        found = active_dataset(session)
    assert found is not None
    assert found.id == max(first, second)


