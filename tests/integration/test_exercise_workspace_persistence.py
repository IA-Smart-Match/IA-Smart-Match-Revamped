def test_entering_twice_returns_one_workspace(
    exercise_sessions: sessionmaker[Session],
) -> None:
    repository = ExerciseWorkspaceRepository()
    with exercise_sessions() as session:
        dataset_id = _insert_dataset(session, label="entering-twice")
        first = repository.get_or_create_workspace(
            session, dataset_id=dataset_id, team_number=3, workspace_secret=_SECRET
        )
        session.commit()
        second = repository.get_or_create_workspace(
            session, dataset_id=dataset_id, team_number=3, workspace_secret=_SECRET
        )
        session.commit()
        assert first == second
        count = session.execute(
            sa.select(sa.func.count()).select_from(schema.exercise_team_workspace)
        ).scalar_one()
    assert count == 1


def test_two_concurrent_entries_for_team_three_yield_one_row(
    exercise_sessions: sessionmaker[Session],
) -> None:
    """The race, run as a race rather than described as one.

    Two sessions, two open transactions, both inserting before either commits.
    PostgreSQL blocks the second on the unique index until the first commits and
    then discards it — which is what ``ON CONFLICT DO NOTHING`` means under
    concurrency — and both read back the same row.
    """
    repository = ExerciseWorkspaceRepository()
    with exercise_sessions() as setup:
        dataset_id = _insert_dataset(setup, label="the-race")

    with exercise_sessions() as one, exercise_sessions() as two:
        first = repository.get_or_create_workspace(
            one, dataset_id=dataset_id, team_number=3, workspace_secret=_SECRET
        )
        one.commit()
        second = repository.get_or_create_workspace(
            two, dataset_id=dataset_id, team_number=3, workspace_secret=_SECRET
        )
        two.commit()

    assert first.id == second.id
    with exercise_sessions() as session:
        count = session.execute(
            sa.select(sa.func.count()).select_from(schema.exercise_team_workspace)
        ).scalar_one()
    assert count == 1


def test_the_stored_hash_matches_the_token_derived_from_the_row_that_won(
    exercise_sessions: sessionmaker[Session],
) -> None:
    """The property the whole derived-token design rests on (OQ-CE-08).

    The insert computes the hash from a candidate id that may lose the race.
    What must be true afterwards is that the hash on the *surviving* row is the
    hash of the token derived from the *surviving* id — otherwise the second
    laptop's cookie would address nothing.
    """
    repository = ExerciseWorkspaceRepository()
    with exercise_sessions() as session:
        dataset_id = _insert_dataset(session, label="derivation")
        workspace = repository.get_or_create_workspace(
            session, dataset_id=dataset_id, team_number=2, workspace_secret=_SECRET
        )
        session.commit()
        table = schema.exercise_team_workspace
        stored = session.execute(
            sa.select(table.c.workspace_token_hash).where(table.c.id == workspace.id)
        ).scalar_one()
        expected = hash_workspace_token(
            derive_workspace_token(secret=_SECRET, workspace_id=workspace.id)
        )
        assert stored == expected
        found = repository.find_by_token_hash(session, token_hash=expected)
    assert found == workspace


def test_an_unknown_token_hash_finds_nothing(exercise_sessions: sessionmaker[Session]) -> None:
    repository = ExerciseWorkspaceRepository()
    with exercise_sessions() as session:
        dataset_id = _insert_dataset(session, label="unknown-token")
        repository.get_or_create_workspace(
            session, dataset_id=dataset_id, team_number=1, workspace_secret=_SECRET
        )
        session.commit()
        assert repository.find_by_token_hash(session, token_hash="0" * 64) is None
        # A token derived under a different secret is just as unknown.
        other = hash_workspace_token(
            derive_workspace_token(secret=_SECRET + "-rotated", workspace_id=uuid.uuid4())
        )
        assert repository.find_by_token_hash(session, token_hash=other) is None


def test_each_team_gets_its_own_workspace_and_its_own_seed(
    exercise_sessions: sessionmaker[Session],
) -> None:
    repository = ExerciseWorkspaceRepository()
    with exercise_sessions() as session:
        dataset_id = _insert_dataset(session, label="six-teams")
        workspaces = {
            team: repository.get_or_create_workspace(
                session, dataset_id=dataset_id, team_number=team, workspace_secret=_SECRET
            )
            for team in range(1, 7)
        }
        session.commit()
        seeds = {team: _seed_of(session, ws.id) for team, ws in workspaces.items()}
    assert len({ws.id for ws in workspaces.values()}) == 6
    assert len(set(seeds.values())) == 6, "six teams, six independent chance elements"
    for seed in seeds.values():
        assert 0 <= seed < 2**63, "BIGINT is signed"


