def test_each_team_gets_its_own_workspace_and_its_own_seed(
    exercise_sessions: sessionmaker[Session],
) -> None:
    repository = ExerciseWorkspaceRepository()
    with exercise_sessions() as session:
        dataset_id = _insert_dataset(session, label="six-teams")
        workspaces = {
            team: repository.get_or_create_workspace(
                session, dataset_id=dataset_id, team_number=team, workspace_secret=_SECRET
            )
            for team in range(1, 7)
        }
        session.commit()
        seeds = {team: _seed_of(session, ws.id) for team, ws in workspaces.items()}
    assert len({ws.id for ws in workspaces.values()}) == 6
    assert len(set(seeds.values())) == 6, "six teams, six independent chance elements"
    for seed in seeds.values():
        assert 0 <= seed < 2**63, "BIGINT is signed"


