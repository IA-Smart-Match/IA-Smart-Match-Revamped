def _insert_dataset(
    session: Session, *, label: str, uploaded_at: datetime | None = None, invite_limit: int = 30
) -> uuid.UUID:
    """One ``exercise_dataset`` row, written directly.

    CE-INGEST-CORE owns the repository that writes these for real; this file
    must not anticipate its shape, so it writes the columns the migration
    declares and nothing more.
    """
    dataset_id = uuid.uuid4()
    values: dict[str, object] = {
        "id": dataset_id,
        "label": label,
        "source_filename": f"{label}.csv",
        "row_count": 300,
        "checksum": uuid.uuid4().hex,
        "invite_limit": invite_limit,
    }
    if uploaded_at is not None:
        values["uploaded_at"] = uploaded_at
    session.execute(sa.insert(schema.exercise_dataset).values(**values))
    # One profile and one event, because the overlay, the saved setting and the
    # result run all carry composite foreign keys into them. Not a fixture of
    # the exercise's data — the real 300 arrive with CE-INGEST-CORE — just the
    # two rows a team's work has to hang off.
    session.execute(
        sa.insert(schema.exercise_profile).values(
            dataset_id=dataset_id,
            profile_no=1,
            display_name="A made-up person",
        )
    )
    session.execute(
        sa.insert(schema.exercise_event).values(
            dataset_id=dataset_id,
            event_key="northline",
            name="Northline Analytics",
            sequence=1,
            is_exercise_event=True,
        )
    )
    session.commit()
    return dataset_id


def _seed_of(session: Session, workspace_id: uuid.UUID) -> int:
    table = schema.exercise_team_workspace
    return int(
        session.execute(sa.select(table.c.seed).where(table.c.id == workspace_id)).scalar_one()
    )


